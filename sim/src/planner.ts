// Turn planners with a learned evaluation (the win model, value.ts).
//
// planTurn (one turn of lookahead): a breadth-first search over the mover's own turn (same move
// generator and budget unit as offenseSearch). Every position it reaches is valued as if the turn
// ended there: pass, let the engine run the turn change (checkup, the opponent's draw), and
// evaluate the win model from the opponent's side: value = 1 - P(opponent wins). A finished game is
// worth 1 or 0. The best line is played.
//
// planTurn2 (two turns, disruption-aware): takes the best few distinct end-of-turn positions from
// that search and, for each, plays the opponent's reply several times: the opponent's hidden cards
// (hand and deck, which the mover cannot see) are redealt at random each time and the opponent
// plans its turn with the same one-turn planner, so a reply that disrupts the plan (Knocks Out the
// ready attackers, shuffles the hand away, locks the Active) is found whenever it is good for the
// opponent. Each candidate is scored by the mover's win chance at the start of its next turn, as a
// blend of the average and the lower quartile over the replies: a path that usually gets disrupted
// loses to a slightly weaker one that holds up.
import { CHEAP_GROUPS, features } from './features';
import { LinearModel, Predictor } from './model';
import { groupsFor } from './policy';
import { GameWinner } from './engine';
import { passTurn } from './policy';
import { prizesLeft } from './rules';
import { Rng } from './rng';
import { Spare, Step, children, expandAction, replayStep, stateHash } from './search';
import { energyGap } from './features';
import { mainCandidates } from './sim';
import { Sim, determinize } from './sim';
import { WinModel } from './value';

export interface PlanOptions {
  budget?: number;       // children generated by the search over the turn
  maxMs?: number;
  seed?: number;
  /** other ways to end the turn to compare with the search's (e.g. the offense policy's line) */
  extra?: { sim: Sim; line: string[]; ended: boolean }[];
}

export interface Plan {
  line: string[];
  end: Sim;              // position after the planned line (the turn is not passed yet unless the line ended it)
  ended: boolean;        // the line ended the turn itself (an attack, or the game ended)
  value: number;         // planned value for the mover
  prizes: number;
  positions: number;
  ms: number;
  candidates?: { line: string[]; mean: number; low: number; score: number }[];
}

interface PNode {
  sim?: Sim;
  depth: number;
  stop: number;          // value of ending the turn here
  value: number;
  parent?: PNode;
  via?: Step;            // step from the parent that first reached this node
  viaLabel?: string;
  kids: { node?: PNode; terminal?: number; label: string; step: Step }[];
  expanded: boolean;
}

/** value for `me` of a position where it is the opponent's turn, or the game is over */
function valueFor(win: WinModel, s: Sim, me: number): number {
  if (s.finished) {
    const w = s.state.winner;
    return w === GameWinner.DRAW ? 0.5 : (w === GameWinner.PLAYER_1 ? 0 : 1) === me ? 1 : 0;
  }
  const toMove = s.state.activePlayer;
  const fv = features(s, toMove, CHEAP_GROUPS, { only: new Set(win.m.names) });
  const p = win.prob(fv.names, fv.values);
  return toMove === me ? p : 1 - p;
}

/** How a planner values the end of the mover's turn. `afterTurn` gets the position at the start of
 *  the opponent's turn (or a finished game) and the prizes both players had left when the turn
 *  began; it returns the value for `me`. */
export interface Evaluator {
  afterTurn(s: Sim, me: number, startPrizes: [number, number]): number;
  /** cheaper stand-in for afterTurn used while searching; the best endings are then re-ranked
   *  with afterTurn (optional) */
  quick?(s: Sim, me: number, startPrizes: [number, number]): number;
  /** value for `me` at the start of its next turn (after the opponent's reply), with the prizes
   *  both had left when `me`'s previous turn began */
  atMyTurn(s: Sim, me: number, startPrizes: [number, number]): number;
}

export function winEvaluator(win: WinModel): Evaluator {
  return { afterTurn: (s, me) => valueFor(win, s, me), atMyTurn: (s, me) => valueFor(win, s, me) };
}

/** Two-turn prize race from the models trained so far (policy v1):
 *    prizes taken this turn
 *    - the opponent's predicted prizes on their next turn (defense model, at their turn start)
 *    + gamma * my predicted prizes on my next turn (offense model, at my next turn start with
 *      the opponent's turn passed)
 *  The last term rewards building towards the next turn (benching, Energy, evolving), which
 *  neither single-turn objective does: v0 playouts were passive and ended by deck-out. A won or
 *  lost game counts as +-10 prizes. */
export function raceEvaluator(off: LinearModel, def: LinearModel, gamma = 0.8, seed = 1): Evaluator {
  const po = new Predictor(off), pd = new Predictor(def);
  const go = groupsFor(off), gd = groupsFor(def);
  const oo = new Set(off.names), od = new Set(def.names);
  const quick = (s: Sim, me: number, start: [number, number]): number => {
    if (s.finished) {
      const w = s.state.winner;
      return w === GameWinner.DRAW ? 0 : (w === GameWinner.PLAYER_1 ? 0 : 1) === me ? 10 : -10;
    }
    const taken = start[0] - prizesLeft(s.state.players[me]);
    const lost = start[1] - prizesLeft(s.state.players[1 - me]);
    const fd = features(s, me, gd, { only: od });
    return taken - lost - Math.max(0, pd.predict(fd.names, fd.values));
  };
  return {
    quick,
    afterTurn: (s, me, start) => {
      if (s.finished) {
        const w = s.state.winner;
        return w === GameWinner.DRAW ? 0 : (w === GameWinner.PLAYER_1 ? 0 : 1) === me ? 10 : -10;
      }
      const taken = start[0] - prizesLeft(s.state.players[me]);
      const lost = start[1] - prizesLeft(s.state.players[1 - me]);
      const fd = features(s, me, gd, { only: od });
      const theirs = Math.max(0, pd.predict(fd.names, fd.values));
      const mine = passTurn(s, seed + 17);
      let next = 0;
      if (mine && !mine.finished && mine.state.activePlayer === me) {
        const fo = features(mine, me, go, { only: oo });
        next = Math.max(0, po.predict(fo.names, fo.values));
      }
      return taken - lost - theirs + gamma * next;
    },
    atMyTurn: (s, me, start) => {
      if (s.finished) {
        const w = s.state.winner;
        return w === GameWinner.DRAW ? 0 : (w === GameWinner.PLAYER_1 ? 0 : 1) === me ? 10 : -10;
      }
      // prizes both sides took over the two turns, plus what I can take now
      const taken = start[0] - prizesLeft(s.state.players[me]);
      const lost = start[1] - prizesLeft(s.state.players[1 - me]);
      const fo = features(s, me, go, { only: oo });
      return taken - lost + Math.max(0, po.predict(fo.names, fo.values));
    },
  };
}

interface TurnSearch {
  root: PNode;
  nodes: PNode[];
  /** every way to end the turn that the search found: a searched position + pass, or a line that
   *  ended the turn itself (terminal) */
  endings: { node: PNode; terminal?: { label: string; step: Step; value: number } ; value: number }[];
}

function searchTurn(root: Sim, full: Evaluator, budget: number, maxMs: number, seed: number, rerank = 8): TurnSearch {
  const t0 = Date.now();
  const mover = root.state.activePlayer;
  const start = prizesLeft(root.state.players[mover]);
  const startBoth: [number, number] = [start, prizesLeft(root.state.players[1 - mover])];
  // while searching, the evaluator's quick value if it has one
  const ev: Evaluator = full.quick ? { ...full, afterTurn: full.quick } : full;
  const stopValue = (s: Sim, k: number): number => {
    const after = passTurn(s, seed + k);
    return after ? ev.afterTurn(after, mover, startBoth) : (s.finished ? ev.afterTurn(s, mover, startBoth) : -1e9);
  };
  const memo = new Map<string, PNode>();
  const nodes: PNode[] = [];
  const endings: TurnSearch['endings'] = [];
  const mk = (sim: Sim, depth: number, parent?: PNode, via?: Step, viaLabel?: string): PNode => {
    const key = stateHash(sim.state);
    const hit = memo.get(key);
    if (hit) {
      return hit;
    }
    const stop = stopValue(sim, nodes.length);
    const n: PNode = { sim, depth, stop, value: stop, kids: [], expanded: false, parent, via, viaLabel };
    memo.set(key, n);
    nodes.push(n);
    endings.push({ node: n, value: stop });
    return n;
  };
  const rootNode = mk(root, 0);
  const queue: PNode[] = [rootNode];
  let head = 0, spent = 0;
  while (head < queue.length && spent < budget && Date.now() - t0 < maxMs) {
    const n = queue[head++];
    if (n.expanded || !n.sim) {
      continue;
    }
    const kids = children(n.sim, mover, start, { cheapPass: true });
    spent += Math.max(1, kids.length);
    n.expanded = true;
    for (const c of kids) {
      if (c.kind === 'pass') {
        continue;            // = this node's stop value
      }
      if (c.terminal) {
        const v = ev.afterTurn(c.sim, mover, startBoth);
        n.kids.push({ terminal: v, label: c.label, step: c.step });
        endings.push({ node: n, terminal: { label: c.label, step: c.step, value: v }, value: v });
        continue;
      }
      const m = mk(c.sim, n.depth + 1, n, c.step, c.label);
      if (m !== n) {
        n.kids.push({ node: m, label: c.label, step: c.step });
        if (!m.expanded) {
          queue.push(m);
        }
      }
    }
    if (n !== rootNode) {
      n.sim = undefined;     // memory: positions are rebuilt by replaying the line
    }
  }
  // quiescence: positions left unexpanded also try their payable attacks as ways to end the turn,
  // so a search that ran out of budget still sees the attack it set up (v1 lost to v0 on prizes
  // without this)
  for (const n of nodes) {
    if (n.expanded || !n.sim) {
      continue;
    }
    const act = n.sim.state.players[mover].active;
    const pc = act.getPokemonCard();
    const spare: Spare = {};
    for (const o of mainCandidates(n.sim.state)) {
      if (o.kind !== 'attack' || !pc) {
        continue;
      }
      const atk = pc.attacks.find(a => o.label === `attack ${a.name}`);
      if (atk && energyGap(atk.cost, act) > 0) {
        continue;
      }
      for (const c of expandAction(n.sim, o, mover, start, { branchCap: 4 }, spare)) {
        if (c.terminal) {
          const v = ev.afterTurn(c.sim, mover, startBoth);
          n.kids.push({ terminal: v, label: c.label, step: c.step });
          endings.push({ node: n, terminal: { label: c.label, step: c.step, value: v }, value: v });
        }
      }
    }
    if (n !== rootNode) {
      n.sim = undefined;
    }
  }
  // re-rank the best endings with the full value (e.g. the race's next-turn term)
  if (full.quick && rerank > 0) {
    const top = endings.slice().sort((a, b) => b.value - a.value).slice(0, rerank);
    for (const e of top) {
      const r = replayEnding(root, e.node, e.terminal);
      const after = r ? (r.ended || r.sim.finished ? r.sim : passTurn(r.sim, seed + 3)) : undefined;
      if (!after) {
        continue;
      }
      e.value = full.afterTurn(after, mover, startBoth);
      if (e.terminal) {
        e.terminal.value = e.value;
        const k = e.node.kids.find(x => x.terminal !== undefined && x.label === e.terminal!.label);
        if (k) {
          k.terminal = e.value;
        }
      } else {
        e.node.stop = e.value;
      }
    }
    // endings not re-ranked keep their quick value: rank them below the re-ranked ones
    const reranked = new Set(top);
    const floor = Math.min(...top.map(e => e.value));
    for (const e of endings) {
      if (!reranked.has(e) && e.value > floor) {
        e.value = floor - 1e-6;
      }
    }
  }
  for (let pass = 0; pass < 2; pass++) {
    for (let i = nodes.length - 1; i >= 0; i--) {
      const n = nodes[i];
      let v = n.stop;
      for (const k of n.kids) {
        v = Math.max(v, k.terminal ?? k.node!.value);
      }
      n.value = v;
    }
  }
  return { root: rootNode, nodes, endings };
}

/** Replay the line that reaches `node` (then `terminal`, if given) from `root`. */
function replayEnding(root: Sim, node: PNode, terminal?: { label: string; step: Step }): { sim: Sim; line: string[]; ended: boolean } | undefined {
  const path: PNode[] = [];
  for (let n: PNode | undefined = node; n && n.parent; n = n.parent) {
    path.unshift(n);
  }
  const mover = root.state.activePlayer;
  const start = prizesLeft(root.state.players[mover]);
  let cur = root;
  const line: string[] = [];
  for (const n of path) {
    const c = replayStep(cur, n.via!, mover, start);
    if (!c) {
      return undefined;
    }
    cur = c.sim;
    line.push(n.viaLabel!);
  }
  if (terminal) {
    const c = replayStep(cur, terminal.step, mover, start);
    if (!c) {
      return undefined;
    }
    return { sim: c.sim, line: [...line, terminal.label], ended: true };
  }
  return { sim: cur, line, ended: false };
}

export function planTurn(root: Sim, ev: WinModel | Evaluator, opts: PlanOptions = {}): Plan {
  const t0 = Date.now();
  const mover = root.state.activePlayer;
  const start = prizesLeft(root.state.players[mover]);
  const e = ev instanceof WinModel ? winEvaluator(ev) : ev;
  const ts = searchTurn(root, e, opts.budget ?? 100, opts.maxMs ?? 5000, opts.seed ?? 1);
  const best = ts.endings.reduce((a, b) => (b.value > a.value ? b : a));
  let r = replayEnding(root, best.node, best.terminal) ?? { sim: root, line: [], ended: false };
  let value = best.value;
  // compare with the given alternatives (ties go to the alternative: it is the tactical line)
  const startBoth: [number, number] = [start, prizesLeft(root.state.players[1 - mover])];
  for (const x of opts.extra ?? []) {
    const after = x.ended || x.sim.finished ? x.sim : passTurn(x.sim, (opts.seed ?? 1) + 5);
    if (!after) {
      continue;
    }
    const v = e.afterTurn(after, mover, startBoth);
    if (v >= value) {
      value = v;
      r = { sim: x.sim, line: x.line, ended: x.ended || x.sim.finished || x.sim.state.activePlayer !== mover };
    }
  }
  return { line: r.line, end: r.sim, ended: r.ended, value, prizes: start - prizesLeft(r.sim.state.players[mover]), positions: ts.nodes.length, ms: Date.now() - t0 };
}

/** Redeal the cards `viewer` cannot see: the opponent's hand and deck are shuffled together and
 *  dealt back in the same sizes; then every deck gets a new hidden order (a new chance seed). The
 *  same card objects move, so the game stays valid. */
export function resampleHidden(sim: Sim, viewer: number, rng: Rng): void {
  const op = sim.state.players[1 - viewer];
  const pool = rng.shuffle([...op.hand.cards, ...op.deck.cards]);
  const h = op.hand.cards.length;
  op.hand.cards = pool.slice(0, h);
  op.deck.cards = pool.slice(h);
  determinize(sim, rng.int(0, 0x7fffffff));
}

export interface Plan2Options extends PlanOptions {
  candidates?: number;   // end-of-turn positions to test against replies
  replies?: number;      // sampled opponent replies per candidate
  replyBudget?: number;  // the opponent planner's budget
  risk?: number;         // weight of the lower quartile in the score (0 = average only)
}

export function planTurn2(root: Sim, ev: WinModel | Evaluator, opts: Plan2Options = {}): Plan {
  const t0 = Date.now();
  const mover = root.state.activePlayer;
  const start = prizesLeft(root.state.players[mover]);
  const startBoth: [number, number] = [start, prizesLeft(root.state.players[1 - mover])];
  const seed = opts.seed ?? 1;
  const rng = new Rng(seed * 7919 + 3);
  const e = ev instanceof WinModel ? winEvaluator(ev) : ev;
  const ts = searchTurn(root, e, opts.budget ?? 100, opts.maxMs ?? 5000, seed);
  // the best few distinct ways to end the turn, by their one-turn value
  const sorted = ts.endings.slice().sort((a, b) => b.value - a.value);
  const picked: { e: TurnSearch['endings'][number]; sim: Sim; line: string[]; ended: boolean; after: Sim }[] = [];
  const seen = new Set<string>();
  for (const e of sorted) {
    if (picked.length >= (opts.candidates ?? 4)) {
      break;
    }
    const r = replayEnding(root, e.node, e.terminal);
    if (!r) {
      continue;
    }
    const after = r.ended ? r.sim : passTurn(r.sim, seed + picked.length);
    if (!after) {
      continue;
    }
    const k = stateHash(after.state);
    if (seen.has(k)) {
      continue;
    }
    seen.add(k);
    picked.push({ e, sim: r.sim, line: r.line, ended: r.ended, after });
  }
  for (const x of opts.extra ?? []) {
    const after = x.ended || x.sim.finished ? x.sim : passTurn(x.sim, seed + 5);
    if (after && !seen.has(stateHash(after.state))) {
      seen.add(stateHash(after.state));
      picked.push({ e: sorted[0], sim: x.sim, line: x.line, ended: x.ended || x.sim.finished || x.sim.state.activePlayer !== mover, after });
    }
  }
  if (!picked.length) {
    return { ...planTurn(root, e, opts), ms: Date.now() - t0 };
  }
  const risk = opts.risk ?? 0.5;
  const scored = picked.map(p => {
    const vals: number[] = [];
    if (p.after.finished) {
      vals.push(e.atMyTurn(p.after, mover, startBoth));
    } else {
      for (let i = 0; i < (opts.replies ?? 4); i++) {
        const s = p.after.copy(rng.fork());
        resampleHidden(s, mover, rng);
        // the opponent plans its reply with the same evaluator, from its side
        const reply = planTurn(s, e, { budget: opts.replyBudget ?? 60, maxMs: 2000, seed: seed + 101 * i });
        let next: Sim | undefined = reply.end;
        if (!reply.ended && !next.finished) {
          next = passTurn(next, seed + 977 * i);
        }
        vals.push(next ? e.atMyTurn(next, mover, startBoth) : e.afterTurn(p.after, mover, startBoth));
      }
    }
    vals.sort((a, b) => a - b);
    const mean = vals.reduce((s, v) => s + v, 0) / vals.length;
    const low = vals[Math.floor((vals.length - 1) / 4)];
    return { p, mean, low, score: (1 - risk) * mean + risk * low };
  });
  scored.sort((a, b) => b.score - a.score);
  const best = scored[0];
  return {
    line: best.p.line, end: best.p.sim, ended: best.p.ended, value: best.score, prizes: start - prizesLeft(best.p.sim.state.players[mover]),
    positions: ts.nodes.length, ms: Date.now() - t0,
    candidates: scored.map(s => ({ line: s.p.line, mean: s.mean, low: s.low, score: s.score })),
  };
}
